# Модель проверки коннектора: строки только в одинарных кавычках, $…$ не понимает,
# ; вне кавычек делит запрос. Каждое предложение должно начинаться с известного слова.
import re
def куски(з):
    пр, тек, внутри = [], '', False
    for с in з:
        if с == "'": внутри = not внутри
        if с == ';' and not внутри: пр.append(тек); тек = ''
        else: тек += с
    пр.append(тек)
    return [п.strip() for п in пр if п.strip()], внутри
def годен(з):
    пр, открыта = куски(з)
    плохие = [п[:50] for п in пр if not re.match(r'(?i)(select|insert|update|with)\b', п)]
    return not плохие and not открыта, плохие, открыта
